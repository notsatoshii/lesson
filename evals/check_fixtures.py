#!/usr/bin/env python3
"""Confirm the eval fixtures' planted mechanical defects without running Claude.

Usage: python evals/check_fixtures.py [--build] [--json]

For each case folder in evals/ that has workspace/docs/lessons/<slug>/plan.md it:
  1. runs tools/timing.py on the plan and checks the expected result (only the over-time fixture
     may fail timing; every other fixture must pass it, so no defect is planted by accident);
  2. runs tools/lint.py (when present) from the case's workspace, with its lesson.md as --house,
     and checks the expected severity-1 rules and locations (the control must be clean);
  3. checks that scaffold.sh matches workspace/ (--build rewrites it from workspace/);
  4. runs every regex grader against a sample finding line it should match, and planted graders
     against a control sample they must not match;
  5. checks trigger-queries.json (20 queries, 8 to 12 of each kind, no duplicates).
Exit 0 when every expectation holds, 1 otherwise.
"""
import argparse
import json
import re
import subprocess
import sys
from pathlib import Path

EVALS = Path(__file__).resolve().parent
TOOLS = EVALS.parent / "tools"
DELIM = "LESSON_FIXTURE_EOF"

# What the tools must report per case. timing: True = must pass, or a list of substrings every one of
# which must appear in a FAIL line. lint: "clean" = exit 0, or a list of (rule, text) pairs that must
# each appear as a severity-1 finding whose location or issue contains the text.
EXPECT = {
    "planted-overtime-lecture": {
        "timing": ["OVER by 12", "passive stretch 20 min (S2)", "longest segment S2 is 20 min"],
        "lint": "clean",
    },
    "planted-agenda-leaderboard": {"timing": True, "lint": "clean"},
    "planted-statistic-guarantee": {"timing": True, "lint": [("forbidden-word", "S6")]},
    "planted-media-no-brief": {"timing": True, "lint": [("media-brief-missing", "M3")]},
    "planted-translationese": {"timing": True, "lint": [("forbidden-word", "S1")]},
    "control-clean": {"timing": True, "lint": "clean"},
}

# A finding line each grader must match (cycle report) or a finding object (critic JSON).
SAMPLE_REPORT = {
    "planted-overtime-lecture": "- [1] [2] [01, +04] Segments · segments sum to 57 min against 45: OVER by 12\n"
                                "- [2] [1] [04] S2 · 20-minute lecture, passive cap 7\n",
    "planted-agenda-leaderboard": "- [2] [1] [05] S1 · the hook is an agenda read aloud\n"
                                  "- [1] [1] [05] Game layer · 10 points for attendance\n"
                                  "- [1] [1] [05] S6 · public leaderboard of individuals in band B\n",
    "planted-statistic-guarantee": "- [1] [2] [01, +08] S2 · the 68% statistic has no source\n"
                                   "- [1] [1] [01] S6 · 보장 is a forbidden word\n",
    "planted-media-no-brief": "- [1] [2] [01, +07] M3 · media row has no brief in media/\n",
    "planted-translationese": "- [1] [1] [01] S1 · 당신 is forbidden\n- [2] [1] [08] S2 · noun stack and 되어지다\n",
    "control-clean": "- [2] [1] [02] S3 · feedback line could name the next step\n- [3] [1] [08] S1 · polish\n",
}
SAMPLE_JSON = {
    "01": '{"findings":[{"severity": 1, "location": "Segments", "issue": "segments sum to 57, budget 45, over by 12"},'
          '{"severity": 1, "location": "S2", "issue": "68% 통계에 출처가 없습니다"}]}',
    "04": '{"findings":[{"severity": 2, "location": "S2", "issue": "20 minutes passive"}]}',
    "05": '{"findings":[{"location": "S6", "severity": 1, "issue": "public leaderboard ranks individuals"},'
          '{"severity": 2, "location": "Game layer", "issue": "points for attendance"}]}',
    "07": '{"findings":[{"severity": 1, "location": "M3", "issue": "no brief"}]}',
    "08": '{"findings":[{"severity": 1, "location": "S6 | line 87", "issue": "보장"},'
          '{"severity": 2, "location": "S2", "issue": "reads as translated"}]}',
}


def run(cmd, cwd):
    p = subprocess.run(cmd, cwd=cwd, capture_output=True)
    return p.returncode, p.stdout.decode("utf-8", "replace"), p.stderr.decode("utf-8", "replace")


def build_scaffold(workspace):
    files = sorted(f for f in workspace.rglob("*") if f.is_file())
    out = [
        "#!/usr/bin/env bash",
        "# Generated by evals/check_fixtures.py --build from workspace/. Edit workspace/, then rebuild.",
        "# Writes the fixture into the eval run's empty workspace (claude plugin eval ... --scaffold).",
        "set -euo pipefail",
    ]
    dirs = sorted({f.parent.relative_to(workspace).as_posix() for f in files} - {"."})
    for d in dirs:
        out.append(f"mkdir -p '{d}'")
    for f in files:
        text = f.read_text(encoding="utf-8").replace("\r\n", "\n")
        if DELIM in text:
            raise SystemExit(f"{f}: contains the heredoc delimiter {DELIM}")
        rel = f.relative_to(workspace).as_posix()
        out.append(f"cat > '{rel}' <<'{DELIM}'")
        out.append(text[:-1] if text.endswith("\n") else text)
        out.append(DELIM)
    return "\n".join(out) + "\n"


def check_case(case_dir, build):
    name = case_dir.name
    exp = EXPECT.get(name)
    ws = case_dir / "workspace"
    plans = sorted(ws.glob("docs/lessons/*/plan.md"))
    res = {"case": name, "ok": True, "lines": []}

    def bad(msg):
        res["ok"] = False
        res["lines"].append(f"  FAIL {msg}")

    def good(msg):
        res["lines"].append(f"  ok   {msg}")

    if exp is None:
        bad("no expectations in check_fixtures.EXPECT")
        return res
    if len(plans) != 1:
        bad(f"expected one workspace/docs/lessons/<slug>/plan.md, found {len(plans)}")
        return res
    plan = plans[0]
    rel = plan.relative_to(ws).as_posix()
    if not (plan.parent / "brief.md").exists():
        bad(f"no brief.md beside {rel} (--skip-interview needs it)")

    # timing
    code, out, err = run([sys.executable, str(TOOLS / "timing.py"), rel, "--json"], ws)
    try:
        t = json.loads(out)
    except json.JSONDecodeError:
        bad(f"timing.py gave no JSON: {err.strip() or out.strip()}")
        t = None
    if t is not None:
        summary = f"timing {t['timing']['status']}, longest passive {t['longest_passive']['min']:g} min, " \
                  f"longest segment {t['longest_segment']['id']} {t['longest_segment']['min']:g} min"
        if exp["timing"] is True:
            (good if t["ok"] else bad)(f"timing.py passes as expected ({summary})" if t["ok"]
                                       else f"timing.py fails but should pass: {'; '.join(t['failures'])}")
        else:
            missing = [s for s in exp["timing"] if not any(s in f for f in t["failures"])]
            if t["ok"] or missing:
                bad(f"timing.py should fail with {exp['timing']}; missing {missing}; got {t['failures']}")
            else:
                good(f"timing.py fails as planted ({len(t['failures'])} checks): {' | '.join(t['failures'])}")

    # lint
    lint = TOOLS / "lint.py"
    if not lint.exists():
        res["lines"].append("  skip lint.py not present")
    else:
        cmd = [sys.executable, str(lint), rel, "--json"]
        if (ws / "lesson.md").exists():
            cmd += ["--house", "lesson.md"]
        code, out, err = run(cmd, ws)
        try:
            lj = json.loads(out)
        except json.JSONDecodeError:
            bad(f"lint.py gave no JSON (exit {code}): {err.strip()[:200] or out.strip()[:200]}")
            lj = None
        if lj is not None:
            sev1 = [f for f in lj.get("findings", []) if f.get("severity") == 1]
            sev2 = [f for f in lj.get("findings", []) if f.get("severity") == 2]
            if exp["lint"] == "clean":
                if sev1 or code != 0:
                    bad(f"lint.py should be clean of severity 1; got {[(f['rule'], f['location']) for f in sev1]}")
                else:
                    good(f"lint.py clean of severity 1 ({len(sev2)} severity-2 notes)")
            else:
                for rule, text in exp["lint"]:
                    hit = [f for f in sev1 if f.get("rule") == rule and (text in f.get("location", "") or text in f.get("issue", ""))]
                    if hit:
                        good(f"lint.py severity 1 [{rule}] at {hit[0]['location']} as planted ({len(sev1)} severity-1 in all)")
                    else:
                        bad(f"lint.py should report severity 1 [{rule}] at {text}; got {[(f['rule'], f['location']) for f in sev1]}")

    # scaffold
    want = build_scaffold(ws)
    sc = case_dir / "scaffold.sh"
    if build:
        sc.write_bytes(want.encode("utf-8"))
        good("scaffold.sh rebuilt from workspace/")
    elif not sc.exists():
        bad("scaffold.sh missing; run with --build")
    elif sc.read_bytes().decode("utf-8") != want:
        bad("scaffold.sh is stale; run with --build")
    else:
        good("scaffold.sh matches workspace/")
    return res


def grader_fields(text):
    fm = text.split("---", 2)[1] if text.startswith("---") else ""
    get = lambda k: (re.search(rf"^{k}:\s*(.*)$", fm, re.M) or [None, None])[1]
    pat = get("pattern")
    if pat and pat.startswith("'") and pat.endswith("'"):
        pat = pat[1:-1].replace("''", "'")
    path = re.search(r"^\s+path:\s*(.+)$", fm, re.M)
    return {"type": get("type"), "pattern": pat, "flags": get("flags") or "", "match": get("match"),
            "path": path.group(1).strip() if path else get("path")}


def check_graders(cases):
    lines, ok = [], True
    for case_dir in cases:
        for g in sorted((case_dir / "graders").glob("*.md")):
            f = grader_fields(g.read_text(encoding="utf-8"))
            if f["type"] != "regex":
                continue
            fl = (re.M if "m" in f["flags"] else 0) | (re.I if "i" in f["flags"] else 0)
            if f["path"].endswith("cycle-1.md"):
                sample = SAMPLE_REPORT.get(case_dir.name, "")
            else:
                sample = SAMPLE_JSON.get(re.search(r"critic-(\d\d)", f["path"]).group(1), "")
            hit = re.search(f["pattern"], sample, fl) is not None
            passed = (not hit) if f["match"] == "not_contains" else hit
            neg = False
            if f["match"] != "not_contains" and f["path"].endswith("cycle-1.md") and case_dir.name != "control-clean":
                neg = re.search(f["pattern"], SAMPLE_REPORT["control-clean"], fl) is not None
            if passed and not neg:
                continue
            ok = False
            lines.append(f"  FAIL {case_dir.name}/graders/{g.name}: " + ("matches the control sample" if neg else "does not match its sample"))
    n = sum(1 for c in cases for _ in (c / "graders").glob("*.md"))
    lines.insert(0, f"  {'ok  ' if ok else 'FAIL'} regex graders behave on sample findings ({n} graders in {len(cases)} cases)")
    return ok, lines


def check_triggers():
    p = EVALS / "trigger-queries.json"
    if not p.exists():
        return False, ["  FAIL trigger-queries.json missing"]
    items = json.loads(p.read_text(encoding="utf-8"))
    pos = sum(1 for i in items if i.get("should_trigger") is True)
    neg = sum(1 for i in items if i.get("should_trigger") is False)
    dup = len(items) - len({i["query"] for i in items})
    ok = len(items) == 20 and 8 <= pos <= 12 and 8 <= neg <= 12 and dup == 0
    return ok, [f"  {'ok  ' if ok else 'FAIL'} trigger-queries.json: {len(items)} queries, {pos} should trigger, {neg} should not, {dup} duplicates"]


def main():
    ap = argparse.ArgumentParser(description="Check the eval fixtures with the mechanical tools only.")
    ap.add_argument("--build", action="store_true", help="rewrite each case's scaffold.sh from its workspace/")
    ap.add_argument("--json", action="store_true")
    a = ap.parse_args()

    cases = sorted(d for d in EVALS.iterdir() if (d / "workspace").is_dir() and (d / "prompt.md").exists())
    results = [check_case(d, a.build) for d in cases]
    gok, glines = check_graders(cases)
    tok, tlines = check_triggers()
    all_ok = all(r["ok"] for r in results) and gok and tok
    if a.json:
        out = json.dumps({"ok": all_ok, "cases": results, "graders": glines, "triggers": tlines}, ensure_ascii=False, indent=1)
    else:
        lines = []
        for r in results:
            lines.append(f"{'PASS' if r['ok'] else 'FAIL'} {r['case']}")
            lines += r["lines"]
        lines.append(f"{'PASS' if gok else 'FAIL'} graders")
        lines += glines
        lines.append(f"{'PASS' if tok else 'FAIL'} triggers")
        lines += tlines
        lines.append("all fixtures as planted" if all_ok else "some expectations failed")
        out = "\n".join(lines)
    sys.stdout.buffer.write((out + "\n").encode("utf-8"))
    sys.exit(0 if all_ok else 1)


if __name__ == "__main__":
    main()
